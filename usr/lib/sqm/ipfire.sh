SQM_SETTINGS="${SQM_SETTINGS:-/var/ipfire/sqm/settings}"
QOS_SETTINGS="${QOS_SETTINGS:-/var/ipfire/qos/settings}"
RED_IFACE_FILE="${RED_IFACE_FILE:-/var/ipfire/red/iface}"
RED_ACTIVE_FILE="${RED_ACTIVE_FILE:-/var/ipfire/red/active}"
NETWORK_AQM="${NETWORK_AQM:-/lib/udev/network-aqm}"

sqm_ipfire_log() {
	logger -t sqm "$*"
	echo "sqm: $*" >&2
}

sqm_read_hash() {
	# KEY=VALUE lines; values are unquoted IPFire hashes.
	file="$1"
	[ -f "$file" ] || return 1
	while IFS= read -r line || [ -n "$line" ]; do
		case "$line" in
			''|\#*) continue ;;
		esac
		key="${line%%=*}"
		val="${line#*=}"
		case "$key" in
			*[!A-Za-z0-9_]*|'') continue ;;
		esac
		# shellcheck disable=SC2163
		export "$key=$val"
	done < "$file"
}

sqm_qos_enabled() {
	qos_en=""
	if [ -f "$QOS_SETTINGS" ]; then
		qos_en=$(sed -n 's/^ENABLED=//p' "$QOS_SETTINGS" | tr -d '\r' | tail -n 1)
	fi
	[ "$qos_en" = "on" ]
}

sqm_valid_iface() {
	case "$1" in
		''|*[!A-Za-z0-9_.:-]*) return 1 ;;
		*) return 0 ;;
	esac
}

sqm_red_iface() {
	if [ -f "$RED_IFACE_FILE" ]; then
		tr -d ' \t\r\n' < "$RED_IFACE_FILE"
	fi
}

sqm_red_is_up() {
	iface="$1"
	[ -n "$iface" ] || return 1
	[ -d "/sys/class/net/${iface}" ] || return 1
	# IPFire creates red/active when the WAN link is established.
	if [ -f "$RED_ACTIVE_FILE" ]; then
		return 0
	fi
	# Fallback: operstate up
	if [ -f "/sys/class/net/${iface}/operstate" ]; then
		state=$(cat "/sys/class/net/${iface}/operstate" 2>/dev/null)
		[ "$state" = "up" ] || [ "$state" = "unknown" ]
		return $?
	fi
	return 1
}

sqm_load_modules() {
	for m in ifb sch_ingress act_mirred cls_u32 sch_cake sch_htb sch_fq_codel; do
		if [ ! -d "/sys/module/${m}" ]; then
			modprobe -q "$m" 2>/dev/null || true
		fi
	done
}

sqm_restore_aqm() {
	iface="$1"
	sqm_valid_iface "$iface" || return 0
	if [ -x "$NETWORK_AQM" ]; then
		INTERFACE="$iface" ACTION="add" "$NETWORK_AQM" >/dev/null 2>&1 || true
	fi
}

sqm_cake_script() {
	case "$1" in
		piece_of_cake.qos|layer_cake.qos) return 0 ;;
		*) return 1 ;;
	esac
}

sqm_write_iface_conf() {
	iface="$1"
	conf="/etc/sqm/${iface}.iface.conf"

	nat_i=""
	nat_e=""
	if sqm_cake_script "$SCRIPT"; then
		if [ "$NAT" = "on" ]; then
			nat_i="nat"
			nat_e="nat"
		fi
		if [ "$DUAL_HOST" = "on" ]; then
			nat_i="${nat_i} dual-dsthost ingress"
			nat_e="${nat_e} dual-srchost"
		fi
		if [ "$ACK_FILTER" = "on" ]; then
			nat_e="${nat_e} ack-filter"
		fi
	fi

	iq="$(echo "$nat_i $IQDISC_OPTS" | sed 's/  */ /g' | sed 's/^ //;s/ $//')"
	eq="$(echo "$nat_e $EQDISC_OPTS" | sed 's/  */ /g' | sed 's/^ //;s/ $//')"

	zero_dscp=0
	ignore_dscp=0
	[ "$WASH" = "on" ] && zero_dscp=1

	enabled_flag=1
	[ "$ENABLED" = "on" ] || enabled_flag=0

	umask 077
	cat > "$conf" << EOF
# Generated by sqmctrl from ${SQM_SETTINGS}
# $(date -u +%Y-%m-%dT%H:%M:%SZ)
IFACE=${iface}
UPLINK=${UPLOAD}
DOWNLINK=${DOWNLOAD}
SCRIPT=${SCRIPT}
QDISC=${QDISC}
ENABLED=${enabled_flag}
LINKLAYER=${LINKLAYER}
OVERHEAD=${OVERHEAD}
STAB_MPU=${STAB_MPU}
ZERO_DSCP_INGRESS=${zero_dscp}
IGNORE_DSCP_INGRESS=${ignore_dscp}
IQDISC_OPTS="${iq}"
EQDISC_OPTS="${eq}"
SQM_DEBUG=${SQM_DEBUG:-0}
EOF
	chmod 600 "$conf"
	echo "$conf"
}

sqm_resolve_iface() {
	iface="$INTERFACE"
	if [ -z "$iface" ]; then
		iface=$(sqm_red_iface)
	fi
	if ! sqm_valid_iface "$iface"; then
		sqm_ipfire_log "No valid interface (INTERFACE='$INTERFACE', red='$(sqm_red_iface)')"
		return 1
	fi
	echo "$iface"
}

sqm_prepare() {
	ENABLED=off
	INTERFACE=
	DOWNLOAD=50000
	UPLOAD=10000
	QDISC=cake
	SCRIPT=piece_of_cake.qos
	LINKLAYER=ethernet
	OVERHEAD=18
	STAB_MPU=64
	NAT=on
	DUAL_HOST=on
	WASH=on
	ACK_FILTER=off
	IQDISC_OPTS=
	EQDISC_OPTS=
	SQM_DEBUG=0

	sqm_read_hash "$SQM_SETTINGS" || true

	case "$SCRIPT" in
		piece_of_cake.qos|layer_cake.qos|simple.qos|simplest.qos|simplest_tbf.qos) ;;
		*)
			sqm_ipfire_log "Unknown SCRIPT='$SCRIPT', falling back to piece_of_cake.qos"
			SCRIPT=piece_of_cake.qos
			;;
	esac
	case "$QDISC" in
		cake|fq_codel) ;;
		*) QDISC=cake ;;
	esac
	case "$LINKLAYER" in
		none|ethernet|atm|ptm) ;;
		*) LINKLAYER=ethernet ;;
	esac
	case "$DOWNLOAD" in
		''|*[!0-9]*) DOWNLOAD=0 ;;
	esac
	case "$UPLOAD" in
		''|*[!0-9]*) UPLOAD=0 ;;
	esac
	case "$OVERHEAD" in
		''|*[!0-9]*) OVERHEAD=18 ;;
	esac
	case "$STAB_MPU" in
		''|*[!0-9]*) STAB_MPU=0 ;;
	esac
	case "$SQM_DEBUG" in
		1|on) SQM_DEBUG=1 ;;
		*) SQM_DEBUG=0 ;;
	esac
}
